function numbered(items: string[]): string {
  return items.map((item, index) => `${index + 1}. ${item}：{{${item}}}`).join('\n')
}

function buildTemplateContent(
  definition: CauseTemplateDefinition,
  documentType: EmbeddedDocumentType
): string {
  const section = definition[documentType]
  const isComplaint = documentType === 'complaint'
  const title = isComplaint ? '民事起诉状' : '民事答辩状'
  const partyLabel = isComplaint ? '原告、被告及第三人' : '答辩人及其他当事人'
  const requestHeading = isComplaint ? '诉讼请求和依据' : '答辩事项和依据'
  const factBlock = section.facts?.length
    ? `\n\n## 事实和理由\n${numbered(section.facts)}`
    : ''

  return `# ${title}
（${definition.cause}）

> 使用要求：保持本模板的项目顺序；只写与案件有关的项目。优先从用户材料提取并核实事实，缺失信息使用【待核实：具体事项】标注，不得编造。

## 案号与案由
- 案号：{{案号}}
- 案由：${definition.cause}

## 当事人信息
- ${partyLabel}：自然人应列明姓名、性别、出生日期、民族、工作单位、职务、联系方式、住所地和经常居住地；法人或非法人组织应列明名称、住所地、登记地、法定代表人或主要负责人、统一社会信用代码和组织类型。
- 委托诉讼代理人：{{代理人姓名、单位、职务、联系方式及代理权限}}
- 送达信息：{{送达地址、收件人、联系电话及电子送达方式}}

## ${requestHeading}
${numbered(section.requests)}${factBlock}

## 管辖、保全与其他说明
- 仲裁或法院管辖约定：{{管辖约定}}
- 财产保全情况：{{是否申请及保全信息}}
- 其他需要说明的内容：{{其他说明}}

## 证据清单
{{证据名称、来源、证明目的及页码或份数}}

${isComplaint ? '此致\n\n{{受理法院}}\n\n具状人：{{原告签字或盖章}}' : '答辩人：{{签字或盖章}}'}

日期：{{日期}}`
}

function normalizeQuery(value: string): string {
  return value.toLowerCase().replace(/\s+/g, '')
}

function matchDefinition(query: string): CauseTemplateDefinition | undefined {
  const normalized = normalizeQuery(query)
  let best: { definition: CauseTemplateDefinition; score: number } | undefined

  for (const definition of CAUSE_TEMPLATES) {
    for (const alias of definition.aliases) {
      const normalizedAlias = normalizeQuery(alias)
      if (!normalized.includes(normalizedAlias)) continue
      const score = normalizedAlias.length
      if (!best || score > best.score) best = { definition, score }
    }
  }

  return best?.definition
}

export const EMBEDDED_LEGAL_DOCUMENT_TEMPLATE_COUNT = CAUSE_TEMPLATES.length * 2

export const EMBEDDED_LEGAL_DOCUMENT_CAUSES = CAUSE_TEMPLATES.map(
  (definition) => definition.cause
)

export function resolveEmbeddedLegalDocumentTemplate(input: {
  query: string
  documentType: EmbeddedDocumentType
}): EmbeddedLegalDocumentTemplate | null {
  const definition = matchDefinition(input.query)
  if (!definition) return null

  const section = definition[input.documentType]
  const documentLabel = input.documentType === 'complaint' ? '民事起诉状' : '民事答辩状'
  return {
    id: `embedded-${input.documentType}-${definition.cause}`,
    name: `${documentLabel}（${definition.cause}）`,
    cause: definition.cause,
    documentType: input.documentType,
    sourceFileId: section.sourceFileId,
    content: buildTemplateContent(definition, input.documentType)
  }
}
